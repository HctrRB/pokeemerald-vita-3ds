// ---------- Input (ui_core.c) ----------
typedef struct
{
    uint32_t held, pressed, repeat;   // VITA_BTN_* bits; repeat = pressed + auto-repeat of the d-pad
    bool touching, touchDown, tap;    // tap = released without dragging
    int32_t tx, ty;                   // current touch point (logical pixels)
    int32_t downX, downY;             // where the touch started
    int32_t dragDy;                   // vertical movement this tick while dragging
    bool dragging;
} UiInput;

static inline bool UiHit(const UiInput *in, int32_t x, int32_t y, int32_t w, int32_t h)
{
    return in->tap && in->tx >= x && in->tx < x + w && in->ty >= y && in->ty < y + h;
}

