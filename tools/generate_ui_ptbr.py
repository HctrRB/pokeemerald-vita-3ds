from pathlib import Path
import json,re

root=Path(__file__).resolve().parents[1]
source=root/'tools/ui_ptbr_strings.txt'
pairs={}
for no,line in enumerate(source.read_text(encoding='utf8').splitlines(),1):
    line=line.strip('\ufeff')
    if not line.strip() or line.lstrip().startswith('#'):continue
    if '|' not in line:
        print('SKIP',no,repr(line))
        continue
    en,br=line.split('|',1)
    en=en.rstrip()
    br=br.strip()
    if not en or not br:
        print('SKIP EMPTY',no,repr(line))
        continue
    if en.startswith('% s'):
        en=en.replace('% s','%s',1)
    if len(en)>=180 or len(br)>=256:raise ValueError(('too long',no))
    pairs[en]=br
assert len(pairs)>450,len(pairs)
# Add general exact string aliases with a short UI-localized label
pairs.update({
    'BAG': 'MOCHILA',
    'POKéMON': 'POKéMON',
    'PANEL': 'PAINEL',
    'ITEM': 'ITEM',
    'GAME': 'JOGO',
    'UI LANGUAGE': 'IDIOMA DA INTERFACE',
})
def cstr(s):return json.dumps(s,ensure_ascii=False)
target=root/'src/platform/ui'
h=target/'ui_locale.h'
h.write_text("""// Brazilian Portuguese UI localization of PS Vita-specific panels.
// Set via GENERAL > UI LANGUAGE; does not alter game save language.
#ifndef UI_LOCALE_H
#define UI_LOCALE_H
#include <stdbool.h>
bool UiLocale_IsPortuguese(void);
const char *UiLocale_Translate(const char *text);
#endif
""", encoding='utf8',newline='\n')

table='\n'.join(f'    {{ {cstr(k)}, {cstr(v)} }},' for k,v in sorted(pairs.items(),key=lambda kv:kv[0].encode('utf8')))
out=f'''// Generated by tools/generate_ui_ptbr.py from ui_ptbr_strings.txt.
// A sorted binary-search dictionary keeps rendering overhead low.
// English UI can be selected at runtime without resetting the save.
#include <stddef.h>
#include <string.h>
#include "ui_locale.h"
#include "platform/vita_extras.h"

typedef struct {{ const char *en; const char *pt; }} UiTranslation;
static const UiTranslation kPtBr[] =
{{
{table}
}};
bool UiLocale_IsPortuguese(void)
{{
    return VitaExtras_GetFast(FAST_EXTRA_UI_LANGUAGE) != 0;
}}
const char *UiLocale_Translate(const char *text)
{{
    if (text == NULL || !UiLocale_IsPortuguese())
        return text;
    size_t lo = 0, hi = sizeof(kPtBr) / sizeof(kPtBr[0]);
    while (lo < hi)
    {{
        const size_t mid = lo + (hi - lo) / 2;
        const int cmp = strcmp(text, kPtBr[mid].en);
        if (cmp == 0)
            return kPtBr[mid].pt;
        if (cmp < 0)
            hi = mid;
        else
            lo = mid + 1;
    }}
    return text;
}}
'''
(target/'ui_locale.c').write_text(out,encoding='utf8',newline='\n')
print('Generated',len(pairs),'UI translations',target/'ui_locale.c')

def patch(rel,orig,replacement):
    path=root/rel
    s=path.read_text('utf8')
    if replacement in s: print('Already',rel,repr(replacement[:65]));return
    assert orig in s,(rel,orig[:80])
    new=s.replace(orig,replacement,1)
    path.write_text(new,encoding='utf8',newline='\n')
    print('Patched',rel)

