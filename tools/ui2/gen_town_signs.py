"""Generates src/platform/ui/ui_town_signs.h: the motto of each town / city sign of the game
(data/maps/<Town>/scripts.inc, <Town>_Text_TownSign / _Text_CitySign), shown under the zone name
by the new UI's zone sign. Run from the repository root:

    python tools/ui2/gen_town_signs.py [--root <tree>]

--root reads and writes another tree: tools/locales/localize.py runs it on a translated build's
staging tree, whose signs are the ROM's own bytes (.byte lines, decoded with charmap.txt).
"""
import argparse
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "src", "platform", "ui", "ui_town_signs.h")
TOWNS = [("LittlerootTown", "MAPSEC_LITTLEROOT_TOWN"), ("OldaleTown", "MAPSEC_OLDALE_TOWN"),
         ("DewfordTown", "MAPSEC_DEWFORD_TOWN"), ("LavaridgeTown", "MAPSEC_LAVARIDGE_TOWN"),
         ("FallarborTown", "MAPSEC_FALLARBOR_TOWN"), ("VerdanturfTown", "MAPSEC_VERDANTURF_TOWN"),
         ("PacifidlogTown", "MAPSEC_PACIFIDLOG_TOWN"), ("PetalburgCity", "MAPSEC_PETALBURG_CITY"),
         ("SlateportCity", "MAPSEC_SLATEPORT_CITY"), ("MauvilleCity", "MAPSEC_MAUVILLE_CITY"),
         ("RustboroCity", "MAPSEC_RUSTBORO_CITY"), ("FortreeCity", "MAPSEC_FORTREE_CITY"),
         ("LilycoveCity", "MAPSEC_LILYCOVE_CITY"), ("MossdeepCity", "MAPSEC_MOSSDEEP_CITY"),
         ("SootopolisCity", "MAPSEC_SOOTOPOLIS_CITY"), ("EverGrandeCity", "MAPSEC_EVER_GRANDE_CITY")]
# Control codes of a sign's text, written as the .string escapes they come from
CONTROLS = {0xFE: "\\n", 0xFA: "\\l", 0xFB: "\\p"}


def charmap(root):
    """GBA character code -> character, from the one-byte entries of charmap.txt"""
    table = {}
    text = open(os.path.join(root, "charmap.txt"), encoding="utf-8").read()
    for m in re.finditer(r"^'(.)'\s*=\s*([0-9A-Fa-f]{2})\s*$", text, re.M):
        table.setdefault(int(m.group(2), 16), m.group(1))
    table.update(CONTROLS)
    return table


def sign_text(town, root, chars):
    src = open(os.path.join(root, "data", "maps", town, "scripts.inc"), encoding="utf-8").read()
    m = re.search(rf"^{town}_Text_(?:Town|City)Sign:\s*\n((?:\s*\.string \".*\"\s*\n)+)", src, re.M)
    if m is not None:
        text = "".join(re.findall(r'\.string "(.*)"', m.group(1)))
    else:
        # A translated tree: the ROM's bytes, up to the end mark 0xFF
        m = re.search(rf"^{town}_Text_(?:Town|City)Sign:\s*\n\s*\.byte ([0-9A-Fa-fx, ]+)", src, re.M)
        data = [int(b, 16) for b in m.group(1).replace(" ", "").split(",") if b]
        end = data.index(0xFF) if 0xFF in data else len(data)
        text = "".join(chars.get(b, "") for b in data[:end])
    text = text.rstrip("$")
    parts = re.split(r"\\[npl]", text)
    motto = " ".join(p.strip() for p in parts[1:] if p.strip())   # the first line is the town name
    motto = motto.replace("“", '"').replace("”", '"').replace("’", "'").replace("…", "...")
    return motto.replace("\\", "\\\\").replace('"', '\\"')


def main():
    args = argparse.ArgumentParser(description="Generates the town sign mottos")
    args.add_argument("--root", default=ROOT, help="tree to read and write (default: this repository)")
    root = os.path.abspath(args.parse_args().root)
    chars = charmap(root)
    lines = ["// Generated by tools/ui2/gen_town_signs.py from the town / city signs of data/maps.",
             "// Do not edit.", "", "#ifndef UI_TOWN_SIGNS_H", "#define UI_TOWN_SIGNS_H", "",
             "#include \"constants/region_map_sections.h\"", "",
             "static const struct { uint16_t mapSec; const char *motto; } sTownSigns[] = {"]
    for town, sec in TOWNS:
        lines.append(f'    {{ {sec}, "{sign_text(town, root, chars)}" }},')
    lines += ["};", "", "#endif", ""]
    out = os.path.join(root, os.path.relpath(OUT, ROOT))
    text = "\n".join(lines)
    if not os.path.exists(out) or open(out, encoding="utf-8").read() != text:
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print(out)


if __name__ == "__main__":
    main()
