"""Writes tools/locales/en/ui.json: every string of the native UI, the keys of every catalog.

Scans the port's C sources for UI_TR("...") and UI_N("...") (src/platform/ui/ui_locale.h) and lists
each English string once, with the files that use it, so a translator sees where it appears. Then,
for every language in tools/locales/languages.json, reports the strings its ui.json still lacks and
the ones it has that the code no longer uses. Run after changing any UI text:

    python tools/locales/extract_ui.py [--check]

--check writes nothing and exits 1 when en/ui.json is out of date (used by the build).
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SCAN = [os.path.join(ROOT, "src", "platform"), os.path.join(ROOT, "src", "title_screen.c")]
TEMPLATE = os.path.join(HERE, "en", "ui.json")
LANGUAGES = os.path.join(HERE, "languages.json")

CALL = re.compile(r"\bUI_(?:TR|N)\s*\(")
LITERAL = re.compile(r'\s*"((?:[^"\\\n]|\\.)*)"', re.S)
ESCAPES = {"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'", "?": "?", "a": "\a", "0": "\0"}


def unescape(body):
    out, i = [], 0
    raw = body.encode("utf-8")
    while i < len(raw):
        c = raw[i]
        if c != 0x5C:                                   # backslash
            out.append(c)
            i += 1
            continue
        nxt = chr(raw[i + 1])
        if nxt == "x":
            m = re.match(rb"[0-9A-Fa-f]+", raw[i + 2:])
            out.append(int(m.group(0), 16) & 0xFF)
            i += 2 + len(m.group(0))
        elif nxt in "01234567":
            m = re.match(rb"[0-7]{1,3}", raw[i + 1:])
            out.append(int(m.group(0), 8) & 0xFF)
            i += 1 + len(m.group(0))
        else:
            out += ESCAPES[nxt].encode()
            i += 2
    return bytes(out).decode("utf-8")


def strip_comments(text):
    """Comments blanked out (same length, so positions keep their line), string literals kept"""
    out, i, n = list(text), 0, len(text)
    while i < n:
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out[i:j] = " " * (j - i)
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out[i:j] = [c if c == "\n" else " " for c in text[i:j]]
            i = j
        elif text[i] == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            i = j + 1
        elif text[i] == "'":
            j = i + 1
            while j < n and text[j] != "'":
                j += 2 if text[j] == "\\" else 1
            i = j + 1
        else:
            i += 1
    return "".join(out)


def scan():
    """English string -> sorted list of the files using it"""
    files = []
    for top in SCAN:
        if os.path.isfile(top):
            files.append(top)
            continue
        for dirpath, _, names in os.walk(top):
            files += [os.path.join(dirpath, f) for f in names if f.endswith((".c", ".h"))]
    keys, errors = {}, []
    for path in sorted(files):
        if path.endswith("ui_locale.h"):
            continue                                    # the macros' own definitions
        text = strip_comments(open(path, encoding="utf-8").read())
        rel = os.path.relpath(path, ROOT).replace("\\", "/")
        for m in CALL.finditer(text):
            at, parts = m.end(), []
            while True:
                lit = LITERAL.match(text, at)
                if lit is None:
                    break
                parts.append(unescape(lit.group(1)))
                at = lit.end()
            if not parts or not re.match(r"\s*\)", text[at:]):
                line = text.count("\n", 0, m.start()) + 1
                errors.append(f"{rel}:{line}: UI_TR / UI_N takes string literals only")
                continue
            keys.setdefault("".join(parts), set()).add(rel)
    return {k: sorted(v) for k, v in keys.items()}, errors


def main():
    args = argparse.ArgumentParser(description="Extracts the native UI's strings")
    args.add_argument("--check", action="store_true", help="exit 1 if en/ui.json is out of date")
    check = args.parse_args().check
    keys, errors = scan()
    for e in errors:
        print(e)
    if errors:
        sys.exit(1)
    template = {"_comment": "Generated by tools/locales/extract_ui.py from the UI_TR / UI_N strings of the code; "
                            "do not edit. Each key is an English string, with the files that use it.",
                "strings": {k: keys[k] for k in sorted(keys)}}
    text = json.dumps(template, ensure_ascii=False, indent=1) + "\n"
    old = open(TEMPLATE, encoding="utf-8").read() if os.path.exists(TEMPLATE) else ""
    if check:
        if old != text:
            print(f"{TEMPLATE} is out of date: run python tools/locales/extract_ui.py")
            sys.exit(1)
        return
    if old != text:
        os.makedirs(os.path.dirname(TEMPLATE), exist_ok=True)
        with open(TEMPLATE, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print(f"{TEMPLATE}: {len(keys)} strings")
    for lang in json.load(open(LANGUAGES, encoding="utf-8"))["languages"]:
        path = os.path.join(HERE, lang["code"], "ui.json")
        if lang["code"] == "en" or not os.path.exists(path):
            continue
        have = json.load(open(path, encoding="utf-8"))["strings"]
        missing = [k for k in keys if not have.get(k)]
        unused = [k for k in have if k not in keys]
        print(f"  {lang['code']}: {len(keys) - len(missing)} translated, {len(missing)} missing, {len(unused)} no longer used")


if __name__ == "__main__":
    main()
